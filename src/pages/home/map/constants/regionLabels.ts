/**
 * 지도에 표시할 지역명을 다듬는다.
 *
 * 특별시·광역시는 `서울특별시`처럼 길게 쓰면 도형 안에 들어가지 않아
 * 백엔드 상위 지역 목록(`GET /regions`)과 같은 짧은 이름으로 줄인다.
 * 반면 도는 `전라북도`처럼 전체 이름을 그대로 보여 준다.
 *
 * 시/군도 `성남시`처럼 전체 이름을 쓰므로 건드리지 않는다. 다만 지도
 * 데이터가 승격 전 이름으로 남아 있는 곳은 현행 표기로 바로잡는다.
 *
 * 표시 전용 변환이다. 사진 조회 키(`regionPhotos`)와 클릭 경로는 계속
 * GeoJSON 이름을 쓰므로 이 표를 거치지 않는다.
 */
const REGION_LABELS: Record<string, string> = {
  // 특별시 · 광역시 · 특별자치시
  서울특별시: '서울',
  부산광역시: '부산',
  대구광역시: '대구',
  인천광역시: '인천',
  광주광역시: '광주',
  대전광역시: '대전',
  울산광역시: '울산',
  세종특별자치시: '세종',

  // 도는 전체 이름을 쓰지만, 제주만 지도 데이터에 '별'이 중복된
  // 오타(제주특별별자치도)로 들어 있어 그대로 보여 줄 수 없다.
  제주특별별자치도: '제주',

  // 군에서 시로 승격됐는데 지도 데이터가 옛 이름으로 남아 있는 곳
  여주군: '여주시',
  당진군: '당진시',
};

export function toRegionLabel(regionName: string): string {
  return REGION_LABELS[regionName] ?? regionName;
}

/**
 * 지도에 표시할 지역명을 Region API 표기로 바꾼다.
 *
 * 지도 GeoJSON은 `서울특별시`, `충청북도` 같은 정식 명칭을 쓰는데, 백엔드
 * 상위 지역 목록(`GET /regions`)은 `서울`, `충북`처럼 줄인 이름을 쓴다.
 * 화면에 보이는 이름을 백엔드 쪽에 맞춘다.
 *
 * 시/군은 백엔드도 `성남시`처럼 전체 이름을 쓰므로 건드리지 않는다. 다만
 * 지도 데이터가 승격 전 이름으로 남아 있는 곳은 백엔드 표기로 바로잡는다.
 *
 * 표시 전용 변환이다. 사진 조회 키(`regionPhotos`)와 클릭 경로는 계속
 * GeoJSON 이름을 쓰므로 이 표를 거치지 않는다.
 */
const REGION_LABELS: Record<string, string> = {
  // 특별시 · 광역시 · 특별자치시
  서울특별시: '서울',
  부산광역시: '부산',
  대구광역시: '대구',
  인천광역시: '인천',
  광주광역시: '광주',
  대전광역시: '대전',
  울산광역시: '울산',
  세종특별자치시: '세종',

  // 도. 지도 데이터가 개편 전 명칭(강원도·전라북도)과 오타
  // (제주특별별자치도)를 쓰고 있어 그 표기를 키로 둔다.
  경기도: '경기',
  강원도: '강원',
  충청북도: '충북',
  충청남도: '충남',
  전라북도: '전북',
  전라남도: '전남',
  경상북도: '경북',
  경상남도: '경남',
  제주특별별자치도: '제주',

  // 군에서 시로 승격됐는데 지도 데이터가 옛 이름으로 남아 있는 곳
  여주군: '여주시',
  당진군: '당진시',
};

export function toRegionLabel(regionName: string): string {
  return REGION_LABELS[regionName] ?? regionName;
}
